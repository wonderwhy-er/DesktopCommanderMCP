import fs from 'fs'; import os from 'os'; import path from 'path';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dc5-'));
Object.assign(process.env, { DC_DEVICE_CONTEXT_HOME: home, DESKTOP_COMMANDER_DEVICE_CONTEXT: 'nudge', DC_DEVICE_CONTEXT_NO_RUNNING: '1' });
const shop = path.join(home, 'code', 'shop'); fs.mkdirSync(shop, { recursive: true });
fs.writeFileSync(path.join(shop, 'package.json'), '{"name":"shop"}');
fs.mkdirSync(path.join(home, '.claude-server-commander'), { recursive: true });
fs.writeFileSync(path.join(home, '.claude-server-commander', 'device-context-events.jsonl'), JSON.stringify({ t: new Date(Date.now() - 86400e3).toISOString(), origin: 'local', root: shop, kind: 'edit', file: '.env' }) + '\n');
const dc = await import('../../dist/device-context/index.js');
let fails = 0; const check = (n, ok, info = '') => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${n}${ok ? '' : '  ' + String(info).slice(0, 400)}`); if (!ok) fails++; };
const calls = [{ timestamp: '11/21/2026, 14:10:20', toolName: 'edit_block', arguments: { file_path: path.join(shop, '.env'), old_string: 'A', new_string: 'SECRET_CONTENT_LINE' }, output: { content: [{ type: 'text', text: 'ok' }] } }];
const raw = { content: [{ type: 'text', text: `Tool Call History (1 results, 1 total in memory)\n\n${JSON.stringify(calls, null, 2)}` }] };
const r1 = dc.maybeAppendDeviceContext('get_recent_tool_calls', { maxResults: 50 }, raw, {});
const t1 = r1.content.map((c) => c.text).join('\n');
check('card on top of history', t1.startsWith('💡 Recent work on this device'), t1);
check('history compacted under the card', /11\/21\/2026, 14:10 edit_block .*\.env -> ok/.test(t1) && !t1.includes('SECRET_CONTENT_LINE'), t1);
check('original result object untouched', raw.content[0].text.includes('SECRET_CONTENT_LINE'));
const r2 = dc.maybeAppendDeviceContext('get_recent_tool_calls', {}, raw, {});
check('second call within a minute: compact, no second card', !r2.content[0].text.startsWith('💡') && r2.content[0].text.includes('compact'), r2.content[0].text);
const r3 = dc.maybeAppendDeviceContext('get_recent_tool_calls', { format: 'full' }, raw, {});
check('format full keeps raw history', r3.content[0].text.includes('SECRET_CONTENT_LINE'), r3.content[0].text);
process.env.DESKTOP_COMMANDER_DEVICE_CONTEXT = 'off';
const r4 = dc.maybeAppendDeviceContext('get_recent_tool_calls', {}, raw, {});
check('feature off: history unchanged', r4 === raw);
process.env.DESKTOP_COMMANDER_DEVICE_CONTEXT = 'tool';
const r5 = dc.maybeAppendDeviceContext('get_recent_tool_calls', {}, raw, {});
check('tool-only mode: history unchanged', r5 === raw);
console.log(fails ? `${fails} FAILED` : 'all passed'); process.exit(fails ? 1 : 0);
