import { redact } from '../remote-device/diagnostics/redact.js';

export type ActivityPhase = 'plan' | 'progress' | 'done' | 'warning' | 'error';
export interface ActivityAnnouncement { phase: ActivityPhase; message: string; }
type State = 'running' | 'done' | 'error';
interface ActivityRow {
    id: string; tool: string; text: string; state: State; at: number; ms?: number; ai: boolean;
}
interface TerminalOutput { write(data: string): unknown; isTTY?: boolean; columns?: number; rows?: number; }

/** Sanitize untrusted IPC text, including ANSI escapes, before it enters our state. */
export function safeActivityText(value: unknown, max = 160): string {
    if (typeof value !== 'string') return '';
    const clean = value.replace(/\x1b(?:\[[0-?]*[ -/]*[@-~]|\][^\x07]*(?:\x07|\x1b\\))/g, '')
        .replace(/[\x00-\x1f\x7f-\x9f]/g, ' ').replace(/\s+/g, ' ').trim();
    return redact(clean).slice(0, max);
}

/** Operation names are deliberately stable, language-neutral and not generated by a model. */
const TOOL_LABELS: Record<string, string> = {
    list_directory: 'Browse directory', read_file: 'Read file',
    read_multiple_files: 'Read files', get_file_info: 'Inspect file',
    start_process: 'Execute command', read_process_output: 'Read command output',
    interact_with_process: 'Interact with process', force_terminate: 'Stop process',
    list_processes: 'Inspect processes', list_sessions: 'Inspect sessions',
    write_file: 'Write file', edit_block: 'Edit file',
    move_file: 'Move file', create_directory: 'Create directory',
    start_search: 'Search files', get_more_search_results: 'Review search results',
    stop_search: 'Stop search', list_searches: 'Review searches',
    get_config: 'Inspect settings', set_config_value: 'Update settings',
    get_usage_stats: 'Review usage', get_recent_tool_calls: 'Review tool history',
    ping: 'Check connection', write_pdf: 'Generate PDF',
};
export function fallbackDescription(tool: string): string {
    if (!/^[a-zA-Z0-9_.-]{1,128}$/.test(tool)) return 'Unknown operation';
    return TOOL_LABELS[tool] ?? tool.replace(/_/g, ' ');
}

export class ActivityView {
    private readonly history: ActivityRow[] = [];
    private readonly inflight = new Map<string, number>();
    private readonly tty: boolean;
    private readonly useColor: boolean;
    private readonly maxHistory = 1000;
    private readonly maxActive = 4096;
    private completed = 0;
    private failed = 0;
    private dropped = 0;
    private scroll = 0;
    private handlingInput = false;

    constructor(private readonly output: TerminalOutput = process.stdout) {
        this.tty = !!output.isTTY && process.env.DC_ACTIVITY_UI !== 'off';
        this.useColor = this.tty && !process.env.NO_COLOR && process.env.DC_ACTIVITY_COLOR !== 'off' && process.env.TERM !== 'dumb';
    }

    /** Legacy protocol compatibility: AI-written announcements never reach the UI. */
    announce(_value: ActivityAnnouncement): void { /* Intentionally not rendered. */ }

    started(id: string, tool: string, _authoredText?: string): void {
        if (this.inflight.has(id) || this.history.some(row => row.id === id)) return;
        // Remote callers may supply arbitrary MCP names. Normalize before
        // writing to a screen OR a non-interactive terminal.
        const safeTool = /^[a-zA-Z0-9_.-]{1,128}$/.test(tool) ? tool : 'unknown_operation';
        const now = Date.now();
        this.inflight.set(id, now);
        if (this.inflight.size > this.maxActive) {
            const oldest = this.inflight.keys().next().value;
            if (oldest !== undefined) this.inflight.delete(oldest);
            this.dropped++;
        }
        this.history.push({ id, tool: safeTool, text: fallbackDescription(safeTool), state: 'running', at: now, ai: false });
        if (this.scroll > 0) this.scroll++; // Do not shift scrollback during live updates.
        if (this.history.length > this.maxHistory) this.history.shift();
        if (this.tty) this.render();
        else this.output.write('RUN  ' + safeTool + '\n');
    }

    finished(id: string, failed = false): void {
        const at = this.inflight.get(id);
        if (at === undefined) return;
        this.inflight.delete(id);
        const elapsed = Math.max(0, Date.now() - at);
        const row = this.history.find(entry => entry.id === id);
        if (row) {
            row.state = failed ? 'error' : 'done';
            row.ms = elapsed;
        }
        if (failed) this.failed++;
        else this.completed++;
        if (this.tty) this.render();
        else this.output.write((failed ? 'FAIL ' : 'OK   ') + (row?.tool ?? 'operation') + '  ' + elapsed + 'ms\n');
    }

    getSnapshot(): ReadonlyArray<Readonly<ActivityRow>> {
        return this.history.map(row => ({ ...row }));
    }

    getTotals(): Readonly<{ active: number; completed: number; failed: number }> {
        return { active: this.inflight.size, completed: this.completed, failed: this.failed };
    }

    getScroll(): number { return this.scroll; }

    private viewportLength(): number {
        const rows = Math.max(1, this.output.rows || 24);
        return Math.max(0, rows - 9);
    }

    scrollBy(amount: number): void {
        const max = Math.max(0, this.history.length - this.viewportLength());
        this.scroll = Math.max(0, Math.min(max, this.scroll + amount));
        if (!this.handlingInput) this.render();
    }

    scrollTo(edge: 'top' | 'bottom'): void {
        this.scroll = edge === 'top' ? Math.max(0, this.history.length - this.viewportLength()) : 0;
        if (!this.handlingInput) this.render();
    }

    /**
     * Accept raw terminal keyboard and SGR mouse-wheel input.
     * Return true only when the operator explicitly requested quit.
     * Never allow escape sequences to echo as ^[[A/^[[B.
     */
    private inputBuffer = '';
    handleInput(chunk: string): boolean {
        this.handlingInput = true;
        try {
        this.inputBuffer += chunk;
        if (this.inputBuffer.length > 8192) this.inputBuffer = this.inputBuffer.slice(-256);
        while (this.inputBuffer) {
            const input = this.inputBuffer;
            if (input.startsWith('\x1b')) {
                const mouse = /^\x1b\[<(\d+);(\d+);(\d+)([mM])/.exec(input);
                if (mouse) {
                    this.inputBuffer = input.slice(mouse[0].length);
                    const button = Number(mouse[1]);
                    if ((button & 64) !== 0 && mouse[4] === 'M') this.scrollBy(button & 1 ? -3 : 3);
                    continue;
                }
                const csi = /^\x1b\[([0-9;]*)([A-Za-z~])/.exec(input);
                const ss3 = /^\x1bO([A-Za-z])/.exec(input);
                if (csi || ss3) {
                    const sequence = (csi || ss3)!;
                    this.inputBuffer = input.slice(sequence[0].length);
                    const key = sequence[sequence.length - 1];
                    if (key === 'A') this.scrollBy(1);
                    else if (key === 'B') this.scrollBy(-1);
                    else if (key === 'H') this.scrollTo('top');
                    else if (key === 'F') this.scrollTo('bottom');
                    else if (key === '~' && csi) {
                        if (/^(5|5;[0-9]+)$/.test(csi[1])) this.scrollBy(Math.max(1, this.viewportLength() - 1));
                        if (/^(6|6;[0-9]+)$/.test(csi[1])) this.scrollBy(-Math.max(1, this.viewportLength() - 1));
                        if (/^(1|7)$/.test(csi[1])) this.scrollTo('top');
                        if (/^(4|8)$/.test(csi[1])) this.scrollTo('bottom');
                    }
                    continue;
                }
                if (input.length < 32 && (/^\x1b(\[([0-9;<]*)?|O)?$/.test(input))) break;
                this.inputBuffer = input.slice(1);
                continue;
            }
            const char = input[0];
            this.inputBuffer = input.slice(1);
            if (char === 'q' || char === 'Q' || char === '\x03') return true;
            if (char === 'k') this.scrollBy(1);
            if (char === 'j') this.scrollBy(-1);
            if (char === 'g') this.scrollTo('top');
            if (char === 'G') this.scrollTo('bottom');
        }
        return false;
        } finally {
            this.handlingInput = false;
            this.render(); // One redraw per input chunk, even after a key burst.
        }
    }

    refresh(): void { this.render(); }

    private color(code: number, value: string): string {
        return this.useColor ? '\x1b[' + code + 'm' + value + '\x1b[0m' : value;
    }

    private render(): void {
        if (!this.tty) return;
        const width = Math.max(1, Math.min(this.output.columns || 80, 150));
        const height = Math.max(1, this.output.rows || 24);
        const inside = Math.max(0, width - 2);
        const clip = (text: string, size: number): string => text.length <= size ? text : text.slice(0, Math.max(0, size - 1)) + '…';
        if (width < 38 || height < 10) {
            // Keep status useful when the terminal is smaller than our framed
            // layout. Never render outside the physical viewport.
            const totals = this.getTotals();
            const lines = [
                'DC / ACTIVITY',
                'ACTIVE ' + totals.active + '  OK ' + totals.completed + '  ERR ' + totals.failed,
                this.history.length ? 'LAST ' + this.history[this.history.length - 1].text : 'WAITING',
                'Up/Down scroll  Q quit',
            ];
            this.output.write('\x1b[H' + lines.slice(0, height).map(line => clip(line, width)).join('\r\n') + '\x1b[J');
            return;
        }
        const frame = (left: string, fill: string, right: string): string =>
            width < 3 ? fill.repeat(width) : left + fill.repeat(inside) + right;
        const line = (content: string): string => width < 3 ? clip(content, width)
            : '│' + clip(' ' + content, inside).padEnd(inside, ' ') + '│';
        const totals = this.getTotals();
        const maxBody = this.viewportLength();
        const maximum = Math.max(0, this.history.length - maxBody);
        this.scroll = Math.min(this.scroll, maximum);
        const end = this.history.length - this.scroll;
        const start = Math.max(0, end - maxBody);
        const showing = this.history.slice(start, end);
        const body = showing.map(row => {
            const status = row.state === 'running' ? 'RUN' : row.state === 'done' ? 'OK ' : 'ERR';
            const statusColor = row.state === 'running' ? 33 : row.state === 'done' ? 32 : 31;
            const ms = row.ms ?? Math.max(0, Date.now() - row.at);
            const time = ms >= 1000 ? (ms / 1000).toFixed(1) + 's' : ms + 'ms';
            const prefix = ' ' + status + '  ';
            const nameSpace = Math.max(0, inside - prefix.length - time.length - 3);
            const tool = clip(row.text, nameSpace).padEnd(nameSpace, ' ');
            // Apply color to status only, after width calculations.
            const raw = prefix + tool + '  ' + time;
            if (width < 3) return clip(raw, width);
            return '│' + prefix[0] + this.color(statusColor, status) + prefix.slice(4)
                + tool + '  ' + time + ' '.repeat(Math.max(0, inside - raw.length)) + '│';
        });
        const state = totals.active ? 'BUSY' : 'IDLE';
        const header = [
            frame('┌', '─', '┐'),
            line('DESKTOP COMMANDER   /   ACTIVITY'),
            line('STATE: ' + state + '    RUNNING: ' + totals.active + '    SUCCESS: ' + totals.completed + '    ERRORS: ' + totals.failed),
            frame('├', '─', '┤'),
            line(' RECENT OPERATIONS' + (this.scroll ? '  /  SCROLLBACK' : '  /  LIVE')),
        ];
        const footer = [
            frame('├', '─', '┤'),
            line('Up/Down / Wheel: scroll    PgUp/PgDn: page    Home/End    Q: quit'),
            line((this.history.length ? 'HISTORY ' + (start + 1) + '-' + end + '/' + this.history.length : 'WAITING FOR MCP OPERATIONS') +
                (this.dropped ? '    TRACKING LIMIT: ' + this.dropped : '')),
            frame('└', '─', '┘'),
        ];
        const all = [...header, ...body, ...footer];
        // Ensure even a narrow/short terminal never writes past its last cell.
        const visible = all.slice(0, height);
        this.output.write('\x1b[H' + visible.join('\r\n') + '\x1b[J');
    }
}
